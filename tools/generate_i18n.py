#!/usr/bin/env python3
import json
import os
import re
import sys


def escape_cpp(s: str) -> str:
    # Replace backslash first, then quotes, newlines, etc.
    s = s.replace('\\', '\\\\')
    s = s.replace('"', '\\"')
    s = s.replace('\n', '\\n')
    s = s.replace('\r', '')
    return s


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    firmware_dir = os.path.abspath(os.path.join(script_dir, ".."))
    locales_dir = os.path.join(firmware_dir, "locales")
    output_path = os.path.join(firmware_dir, "src", "ui", "i18n_generated.h")

    if not os.path.exists(locales_dir):
        print(f"[i18n] Error: Locales directory not found: {locales_dir}", file=sys.stderr)
        sys.exit(1)

    languages_config = [
        ("EN", "en", "English", "English"),
        ("RU", "ru", "Russian", "Русский"),
        ("ES", "es", "Spanish", "Español"),
        ("DE", "de", "German", "Deutsch"),
        ("FR", "fr", "French", "Français"),
        ("IT", "it", "Italian", "Italiano"),
        ("PT_PT", "pt-PT", "European Portuguese", "Português (Portugal)"),
        ("PT_BR", "pt-BR", "Brazilian Portuguese", "Português (Brasil)"),
        ("ZH_HANS", "zh-Hans", "Simplified Chinese", "简体中文"),
        ("JA", "ja", "Japanese", "日本語"),
        ("KO", "ko", "Korean", "한국어"),
    ]

    en_path = os.path.join(locales_dir, "en.json")
    if not os.path.exists(en_path):
        print(f"[i18n] Error: Base locale file not found: {en_path}", file=sys.stderr)
        sys.exit(1)

    def load_json_relaxed(path):
        with open(path, encoding="utf-8") as f:
            text = f.read()
        text = re.sub(r',\s*([}\]])', r'\1', text)
        return json.loads(text)

    en_data = load_json_relaxed(en_path)

    keys = list(en_data.keys())

    markers = re.compile(r"%[A-Z][A-Z0-9_]*%|%%|%[-+ #0]*\d*(?:\.\d+)?(?:ll|l|z)?[diufscxX]")
    languages = []
    for enum_name, code, name, native_name in languages_config:
        lang_path = os.path.join(locales_dir, f"{code}.json")
        if not os.path.exists(lang_path):
            print(f"[i18n] Warning: Locale file {code}.json not found. Using English fallback.", file=sys.stderr)
            lang_data = dict(en_data)
        else:
            lang_data = load_json_relaxed(lang_path)

            missing = [k for k in keys if k not in lang_data]
            if missing:
                print(
                    f"[i18n] Warning: {len(missing)} keys missing in {code}.json. Using English fallback.",
                    file=sys.stderr,
                )
                for k in missing:
                    lang_data[k] = en_data[k]

        if code not in {"en", "ru", "es"}:
            # Validate the source file, not its English-filled output.
            source = load_json_relaxed(lang_path)
            if source.keys() != en_data.keys():
                sys.exit(f"[i18n] {code}: keys differ from en.json")
            for key in keys:
                val = source[key]
                if not isinstance(val, str) or (en_data[key].strip() and not val.strip()):
                    sys.exit(f"[i18n] {code}: missing translation for {key}")
                if markers.findall(val) != markers.findall(en_data[key]):
                    sys.exit(f"[i18n] {code}: format markers differ for {key}")

        languages.append((enum_name, code, name, native_name, lang_data))

    lines = []
    lines.append("// Auto-generated by tools/generate_i18n.py. DO NOT EDIT DIRECTLY.")
    lines.append("// Source of truth is in locales/*.json (Crowdin compatible).")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append("enum class AppLanguage : uint8_t {")
    for idx, (enum_name, *_) in enumerate(languages):
        lines.append(f"    {enum_name} = {idx},")
    lines.append(f"    COUNT = {len(languages)}")
    lines.append("};")
    lines.append("")
    lines.append("enum class MsgId : uint16_t {")
    for idx, k in enumerate(keys):
        lines.append(f"    {k} = {idx},")
    lines.append(f"    COUNT = {len(keys)}")
    lines.append("};")
    lines.append("")

    # Generate string tables for each language
    for enum_name, code, name, _native_name, lang_dict in languages:
        lines.append(f"// Language: {name} ({code})")
        lines.append(f"static const char* const STRINGS_{enum_name}[(size_t)MsgId::COUNT] PROGMEM = {{")
        for k in keys:
            val = lang_dict.get(k, en_data[k])
            escaped = escape_cpp(val)
            lines.append(f'    /* {k} */ "{escaped}",')
        lines.append("};")
        lines.append("")

    lines.append("static const char* const* const I18N_ALL_TABLES[(size_t)AppLanguage::COUNT] = {")
    for enum_name, _, _, _, _ in languages:
        lines.append(f"    STRINGS_{enum_name},")
    lines.append("};")
    lines.append("")

    lines.append("static const char* const I18N_LANG_CODES[(size_t)AppLanguage::COUNT] = {")
    for _, code, _, _, _ in languages:
        lines.append(f'    "{code}",')
    lines.append("};")
    lines.append("")

    lines.append("static const char* const I18N_LANG_NAMES[(size_t)AppLanguage::COUNT] = {")
    for _, _, _, native_name, _ in languages:
        lines.append(f'    "{native_name}",')
    lines.append("};")
    lines.append("")

    content = "\n".join(lines) + "\n"

    # Only write if file changed
    if os.path.exists(output_path):
        with open(output_path, encoding="utf-8") as f:
            existing = f.read()
        if existing == content:
            print(f"[i18n] Generated header is up to date: {output_path}")
            return

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[i18n] Generated {len(keys)} strings for {len(languages)} languages -> {output_path}")


# Support PlatformIO extra_scripts execution
try:
    Import("env")  # type: ignore[name-defined]  # noqa: F821 (PlatformIO SCons builtin)
    main()
except NameError:
    if __name__ == "__main__":
        main()
