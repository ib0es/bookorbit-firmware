#!/usr/bin/env python3
"""Generates src/ui/kit/ui_fonts.h: the bitmap fonts of the FreeInkUI interface.

Text fonts: Carlito (SIL OFL 1.1) Regular/Bold, one freeink::ui::BitmapFont per
UI font slot, covering U+0020..U+045F. Only ASCII, Latin-1 and Cyrillic
(U+0400..U+045F) are rasterized; the codepoints in between get empty glyphs, so
the table stays one contiguous range (what BitmapFont needs) without paying for
Greek or Latin Extended bitmaps.

Symbols (arrows, check mark, bullet, dashes, numero sign, backspace) come from
DejaVu Sans (Bitstream Vera license) at the same pixel size, as a small sorted
table that ui_kit.cpp serves through DisplayTarget's glyph fallback.

Usage (from firmware/):
    python3 tools/gen_ui_fonts.py [--fonts-dir /usr/share/fonts/truetype]
Needs Pillow. Re-run after changing SIZES or the symbol list.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

# slot, symbol name, TTF (relative to fonts dir), pixel size
SIZES = [
    (0, "UiSmall", "crosextra/Carlito-Regular.ttf", 18),
    (1, "UiBody", "crosextra/Carlito-Regular.ttf", 22),
    (2, "UiTitle", "crosextra/Carlito-Bold.ttf", 26),
    (3, "UiLarge", "crosextra/Carlito-Bold.ttf", 34),
]
SYMBOL_TTF = "dejavu/DejaVuSans.ttf"
FIRST, LAST = 0x20, 0x45F
WANTED = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x400, 0x460))
SYMBOLS = [0x2013, 0x2014, 0x2022, 0x2116, 0x2190, 0x2192, 0x232B, 0x25B2, 0x25B6, 0x25BA,
           0x25BC, 0x25C0, 0x25C4, 0x2713]


def raster(font, ch, ascent):
    """1bpp MSB-first packed bitmap + metrics of one glyph (None if blank)."""
    xadv = round(font.getlength(ch))
    bbox = font.getbbox(ch)
    if bbox is None or bbox[2] - bbox[0] <= 0 or bbox[3] - bbox[1] <= 0:
        return xadv, None
    l, t, r, b = bbox
    img = Image.new("1", (r + 2, b + 2), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    crop = img.crop((l, t, r, b))
    w, h = crop.size
    px = crop.load()
    out = bytearray()
    acc = nbits = 0
    for y in range(h):
        for x in range(w):
            acc = (acc << 1) | (1 if px[x, y] else 0)
            nbits += 1
            if nbits == 8:
                out.append(acc)
                acc = nbits = 0
    if nbits:
        out.append(acc << (8 - nbits))
    return xadv, (bytes(out), w, h, l, t - ascent)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts-dir", default="/usr/share/fonts/truetype")
    ap.add_argument("--out", default="src/ui/kit/ui_fonts.h")
    args = ap.parse_args()

    L = []
    P = L.append
    P("#pragma once")
    P("")
    P("// AUTO-GENERATED by tools/gen_ui_fonts.py - do not edit by hand.")
    P("// Text: Carlito Regular/Bold (SIL Open Font License 1.1), U+0020..U+045F with")
    P("// ASCII, Latin-1 and Cyrillic rasterized. Symbols: DejaVu Sans (Bitstream Vera")
    P("// license). Both licenses permit embedding rasterized bitmaps.")
    P("")
    P("#include <FreeInkUIFont.h>")
    P("")
    P("namespace uikit {")
    P("namespace fonts {")
    P("")
    P("struct SymbolGlyph {")
    P("    uint16_t codepoint;")
    P("    freeink::ui::FontGlyph glyph;")
    P("};")
    P("")
    P("struct SymbolSet {")
    P("    uint8_t pixelSize;  // matches the text font's yAdvance (the fallback key)")
    P("    const uint8_t* bitmap;")
    P("    const SymbolGlyph* glyphs;")
    P("    uint8_t count;")
    P("};")
    P("")
    total = 0
    sym_sets = []
    for slot, name, ttf, size in SIZES:
        path = os.path.join(args.fonts_dir, ttf)
        font = ImageFont.truetype(path, size)
        ascent, descent = font.getmetrics()
        yadv = ascent + descent
        bitmap = bytearray()
        glyphs = []
        maxw = maxh = 0
        for cp in range(FIRST, LAST + 1):
            if cp not in WANTED:
                glyphs.append((0, 0, 0, 0, 0, 0))
                continue
            xadv, g = raster(font, chr(cp), ascent)
            if g is None:
                glyphs.append((len(bitmap), 0, 0, xadv, 0, 0))
                continue
            data, w, h, xo, yo = g
            if len(bitmap) > 0xFFFF:
                sys.exit(f"{name}: bitmap offset overflow at U+{cp:04X}")
            glyphs.append((len(bitmap), w, h, xadv, xo, yo))
            bitmap += data
            maxw, maxh = max(maxw, w), max(maxh, h)
        total += len(bitmap) + len(glyphs) * 7
        P(f"// slot {slot}: {ttf} {size}px, line {yadv}px, ascent {ascent}px, {len(bitmap)} bitmap bytes")
        P(f"inline constexpr uint8_t k{name}Bitmap[] = {{")
        for i in range(0, len(bitmap), 24):
            P("    " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
        P("};")
        P(f"inline constexpr freeink::ui::FontGlyph k{name}Glyphs[] = {{")
        for i in range(0, len(glyphs), 8):
            P("    " + " ".join("{%d,%d,%d,%d,%d,%d}," % g for g in glyphs[i:i + 8]))
        P("};")
        P(f"inline constexpr freeink::ui::BitmapFont k{name}Font{{k{name}Bitmap, k{name}Glyphs, 0x{FIRST:X}, 0x{LAST:X}, "
          f"{yadv}, {ascent}, {maxw}, {maxh}, 1}};")
        P("")

        # Symbols at the same pixel size.
        sfont = ImageFont.truetype(os.path.join(args.fonts_dir, SYMBOL_TTF), size)
        sascent, _ = sfont.getmetrics()
        sbits = bytearray()
        sglyphs = []
        for cp in SYMBOLS:
            xadv, g = raster(sfont, chr(cp), sascent)
            if g is None:
                continue
            data, w, h, xo, yo = g
            sglyphs.append((cp, len(sbits), w, h, xadv, xo, yo))
            sbits += data
        total += len(sbits) + len(sglyphs) * 9
        P(f"inline constexpr uint8_t k{name}SymBitmap[] = {{")
        for i in range(0, len(sbits), 24):
            P("    " + ",".join(f"0x{b:02X}" for b in sbits[i:i + 24]) + ",")
        P("};")
        P(f"inline constexpr SymbolGlyph k{name}SymGlyphs[] = {{")
        for (cp, off, w, h, xadv, xo, yo) in sglyphs:
            P(f"    {{0x{cp:04X}, {{{off},{w},{h},{xadv},{xo},{yo}}}}},")
        P("};")
        sym_sets.append((yadv, name, len(sglyphs)))
        P("")

    P("inline constexpr SymbolSet kSymbolSets[] = {")
    for (yadv, name, n) in sym_sets:
        P(f"    {{{yadv}, k{name}SymBitmap, k{name}SymGlyphs, {n}}},")
    P("};")
    P("")
    P("}  // namespace fonts")
    P("}  // namespace uikit")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {args.out}: ~{total / 1024:.1f} KB of flash")


if __name__ == "__main__":
    main()
