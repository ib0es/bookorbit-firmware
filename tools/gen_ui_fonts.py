#!/usr/bin/env python3
"""Generates src/ui/kit/ui_fonts.h: the bitmap fonts of the FreeInkUI interface.

Text fonts: Noto Sans (SIL OFL 1.1, fonts/sd/NotoSans) Regular/Bold, one freeink::ui::BitmapFont per
UI font slot, covering U+0020..U+045F. Only ASCII, Latin-1 and Cyrillic
(U+0400..U+045F) are rasterized; the codepoints in between get empty glyphs, so
the table stays one contiguous range (what BitmapFont needs) without paying for
Greek or Latin Extended bitmaps.

Symbols (arrows, check mark, bullet, dashes, numero sign, backspace) come from
DejaVu Sans (Bitstream Vera license) at the same pixel size, as a small sorted
table that ui_kit.cpp serves through DisplayTarget's glyph fallback.

Usage (from firmware/):
    python3 tools/gen_ui_fonts.py [--fonts-dir /usr/share/fonts/truetype]
Needs Pillow. Re-run after changing SIZES or the symbol list.

For locale glyphs install fonttools too, and pass --locale-fonts-dir with
sc.otf, jp.otf and kr.otf from the pinned noto-cjk commit below. Upstream
paths: Sans/OTF/{SimplifiedChinese,Japanese,Korean}/NotoSansCJK{sc,jp,kr}-Regular.otf.
License: LICENSES/OFL-1.1-NotoSansCJK.txt.
"""

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# slot, symbol name, TTF (relative to fonts dir), pixel size
# A path starting with "@/" is relative to firmware/ (the fonts kept in the repo).
SIZES = [
    (0, "UiSmall", "@/docs/fonts/NotoSans/NotoSans-Regular.ttf", 18),
    (1, "UiBody", "@/docs/fonts/NotoSans/NotoSans-Regular.ttf", 22),
    (2, "UiTitle", "@/docs/fonts/NotoSans/NotoSans-Bold.ttf", 24),
    (3, "UiLarge", "@/docs/fonts/NotoSans/NotoSans-Bold.ttf", 32),
]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYMBOL_TTF = "dejavu/DejaVuSans.ttf"
FIRST, LAST = 0x20, 0x45F
WANTED = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x400, 0x460)) | {0x152, 0x153}
SYMBOLS = [
    0x2013,
    0x2014,
    0x2022,
    0x2026,
    0x2039,
    0x203A,
    0x2116,
    0x2190,
    0x2192,
    0x232B,
    0x25B2,
    0x25B6,
    0x25BA,
    0x25BC,
    0x25C0,
    0x25C4,
    0x2713,
]


def raster(font, ch, ascent):
    """1bpp MSB-first packed bitmap + metrics of one glyph (None if blank)."""
    xadv = round(font.getlength(ch))
    bbox = font.getbbox(ch)
    if bbox is None or bbox[2] - bbox[0] <= 0 or bbox[3] - bbox[1] <= 0:
        return xadv, None
    l, t, r, b = bbox
    img = Image.new("1", (r + 2, b + 2), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    crop = img.crop((l, t, r, b))
    w, h = crop.size
    px = crop.load()
    out = bytearray()
    acc = nbits = 0
    for y in range(h):
        for x in range(w):
            acc = (acc << 1) | (1 if px[x, y] else 0)
            nbits += 1
            if nbits == 8:
                out.append(acc)
                acc = nbits = 0
    if nbits:
        out.append(acc << (8 - nbits))
    return xadv, (bytes(out), w, h, l, t - ascent)


# Noto Sans CJK Sans2.004, commit 523d033d6cb47f4a80c58a35753646f5c3608a78.
CJK = {
    "zh-Hans": ("sc", "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b", "简体中文"),
    "ja": ("jp", "68a3fc98800b2a27b371f2fb79991daf3633bd89309d4ffaa6946fd587f375b5", "日本語"),
    "ko": ("kr", "6bcb2a0703aa137e874fc2dffa85f6c21ba9a67fa329e81b8c801663af7e992a", "한국어"),
}


def generate_locale_fonts(directory, output):
    from fontTools.ttLib import TTFont

    locales = ["de", "fr", "it", "pt-PT", "pt-BR", *CJK]
    texts = {
        code: "".join(json.loads(Path(ROOT, "locales", code + ".json").read_text(encoding="utf-8")).values())
        for code in locales
    }
    for code, (_, _, name) in CJK.items():
        texts[code] += name
    excluded = WANTED | set(SYMBOLS)
    chars = {code: {ord(ch) for ch in text if ord(ch) > 32 and ord(ch) not in excluded} for code, text in texts.items()}
    paths = {}
    for code, (region, digest, _) in CJK.items():
        path = directory / (region + ".otf")
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            sys.exit(f"Unexpected Noto CJK font: {path}")
        paths[code] = path
    lines = [
        "#pragma once",
        "// Generated by tools/gen_ui_fonts.py --locale-fonts-dir.",
        "#include <stdint.h>",
        "namespace uikit::fonts {",
        "struct LocaleGlyph { uint32_t codepoint, offset; uint8_t width, height, advance; int8_t x, y; };",
        "struct LocaleGlyphSet { uint8_t pixelSize; const char* code; const uint8_t* bitmap; const LocaleGlyph* glyphs; unsigned count; };",
    ]
    sets = []
    latin_chars = set().union(*(chars[c] for c in locales if c not in CJK))
    for slot, _, _, size in SIZES:
        latin = Path(ROOT, "fonts/sd/NotoSans", "NotoSans-" + ("Bold" if slot >= 2 else "Regular") + ".ttf")
        base_font = ImageFont.truetype(str(latin), size)
        ascent, descent = base_font.getmetrics()
        bitmap = bytearray()
        offsets = {}
        for i, (code, path, needed) in enumerate(
            [("", latin, latin_chars), *((c, paths[c], chars[c] - latin_chars) for c in CJK)]
        ):
            font = ImageFont.truetype(str(path), size)
            cmap = TTFont(path).getBestCmap()
            entries = []
            for cp in sorted(needed):
                if cp not in cmap:
                    sys.exit(f"{path}: missing U+{cp:04X} ({chr(cp)})")
                advance, glyph = raster(font, chr(cp), font.getmetrics()[0])
                if glyph is None:
                    sys.exit(f"{path}: empty glyph U+{cp:04X}")
                data, w, h, x, y = glyph
                if max(w, h) > 48:
                    sys.exit(f"{path}: oversized glyph U+{cp:04X}")
                if data not in offsets:
                    offsets[data] = len(bitmap)
                    bitmap.extend(data)
                entries.append(f"    {{0x{cp:X},{offsets[data]},{w},{h},{advance},{x},{y}}},")
            key = f"kLocale{slot}_{i}"
            lines += [f"inline constexpr LocaleGlyph {key}[] = {{", *entries, "};"]
            sets.append(f'    {{{ascent + descent}, "{code}", kLocaleBits{slot}, {key}, {len(entries)}}},')
        lines.append(f"inline constexpr uint8_t kLocaleBits{slot}[] = {{")
        for i in range(0, len(bitmap), 24):
            lines.append("    " + ",".join(f"0x{b:02X}" for b in bitmap[i : i + 24]) + ",")
        lines.append("};")
    lines += ["inline constexpr LocaleGlyphSet kLocaleGlyphSets[] = {", *sets, "};", "}  // namespace uikit::fonts", ""]
    Path(output).write_text("\n".join(lines), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts-dir", default="/usr/share/fonts/truetype")
    ap.add_argument("--out")
    ap.add_argument("--locale-fonts-dir", type=Path, help="Generate sparse locale glyphs using pinned Noto CJK fonts")
    args = ap.parse_args()
    if args.locale_fonts_dir:
        generate_locale_fonts(args.locale_fonts_dir, args.out or "src/ui/kit/ui_locale_fonts.h")
        return
    args.out = args.out or "src/ui/kit/ui_fonts.h"

    L = []
    P = L.append
    P("#pragma once")
    P("")
    P("// AUTO-GENERATED by tools/gen_ui_fonts.py - do not edit by hand.")
    P("// Text: Noto Sans Regular/Bold (SIL Open Font License 1.1), U+0020..U+045F with")
    P("// ASCII, Latin-1 and Cyrillic rasterized. Symbols: DejaVu Sans (Bitstream Vera")
    P("// license). Both licenses permit embedding rasterized bitmaps.")
    P("")
    P("#include <FreeInkUIFont.h>")
    P("")
    P("namespace uikit {")
    P("namespace fonts {")
    P("")
    P("struct SymbolGlyph {")
    P("    uint16_t codepoint;")
    P("    freeink::ui::FontGlyph glyph;")
    P("};")
    P("")
    P("struct SymbolSet {")
    P("    uint8_t pixelSize;  // matches the text font's yAdvance (the fallback key)")
    P("    const uint8_t* bitmap;")
    P("    const SymbolGlyph* glyphs;")
    P("    uint8_t count;")
    P("};")
    P("")
    total = 0
    sym_sets = []
    for slot, name, ttf, size in SIZES:
        path = os.path.join(ROOT, ttf[2:]) if ttf.startswith("@/") else os.path.join(args.fonts_dir, ttf)
        font = ImageFont.truetype(path, size)
        ascent, descent = font.getmetrics()
        yadv = ascent + descent
        bitmap = bytearray()
        glyphs = []
        maxw = maxh = 0
        for cp in range(FIRST, LAST + 1):
            if cp not in WANTED:
                glyphs.append((0, 0, 0, 0, 0, 0))
                continue
            xadv, g = raster(font, chr(cp), ascent)
            if g is None:
                glyphs.append((len(bitmap), 0, 0, xadv, 0, 0))
                continue
            data, w, h, xo, yo = g
            if len(bitmap) > 0xFFFF:
                sys.exit(f"{name}: bitmap offset overflow at U+{cp:04X}")
            glyphs.append((len(bitmap), w, h, xadv, xo, yo))
            bitmap += data
            maxw, maxh = max(maxw, w), max(maxh, h)
        total += len(bitmap) + len(glyphs) * 7
        P(
            f"// slot {slot}: {os.path.basename(ttf)} {size}px, line {yadv}px, ascent {ascent}px, {len(bitmap)} bitmap bytes"
        )
        P(f"inline constexpr uint8_t k{name}Bitmap[] = {{")
        for i in range(0, len(bitmap), 24):
            P("    " + ",".join(f"0x{b:02X}" for b in bitmap[i : i + 24]) + ",")
        P("};")
        P(f"inline constexpr freeink::ui::FontGlyph k{name}Glyphs[] = {{")
        for i in range(0, len(glyphs), 8):
            P("    " + " ".join("{%d,%d,%d,%d,%d,%d}," % g for g in glyphs[i : i + 8]))
        P("};")
        P(
            f"inline constexpr freeink::ui::BitmapFont k{name}Font{{k{name}Bitmap, k{name}Glyphs, 0x{FIRST:X}, 0x{LAST:X}, "
            f"{yadv}, {ascent}, {maxw}, {maxh}, 1}};"
        )
        P("")

        # Symbols at the same pixel size.
        sfont = ImageFont.truetype(os.path.join(args.fonts_dir, SYMBOL_TTF), size)
        sascent, _ = sfont.getmetrics()
        sbits = bytearray()
        sglyphs = []
        for cp in SYMBOLS:
            xadv, g = raster(sfont, chr(cp), sascent)
            if g is None:
                continue
            data, w, h, xo, yo = g
            sglyphs.append((cp, len(sbits), w, h, xadv, xo, yo))
            sbits += data
        total += len(sbits) + len(sglyphs) * 9
        P(f"inline constexpr uint8_t k{name}SymBitmap[] = {{")
        for i in range(0, len(sbits), 24):
            P("    " + ",".join(f"0x{b:02X}" for b in sbits[i : i + 24]) + ",")
        P("};")
        P(f"inline constexpr SymbolGlyph k{name}SymGlyphs[] = {{")
        for cp, off, w, h, xadv, xo, yo in sglyphs:
            P(f"    {{0x{cp:04X}, {{{off},{w},{h},{xadv},{xo},{yo}}}}},")
        P("};")
        sym_sets.append((yadv, name, len(sglyphs)))
        P("")

    P("inline constexpr SymbolSet kSymbolSets[] = {")
    for yadv, name, n in sym_sets:
        P(f"    {{{yadv}, k{name}SymBitmap, k{name}SymGlyphs, {n}}},")
    P("};")
    P("")
    P("}  // namespace fonts")
    P("}  // namespace uikit")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {args.out}: ~{total / 1024:.1f} KB of flash")


if __name__ == "__main__":
    main()
