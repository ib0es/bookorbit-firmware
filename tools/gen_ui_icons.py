#!/usr/bin/env python3
"""Generates src/ui/kit/ui_icons.h: 1-bit bitmaps of the SVG icons in tools/icons.

Each icon is rasterized (rsvg-convert, anti-aliased) at a few sizes and cut at
50 % coverage, so the device draws the size closest to the room it has
(uikit::icon::bitmapIcon) instead of scaling a 1-bit picture.

Icons: Material Symbols (Google, Apache License 2.0), outlined, weight 400.

Usage (from firmware/):
    python3 tools/gen_ui_icons.py
Needs rsvg-convert (librsvg) and Pillow. Re-run after adding an icon or a size.
"""

import os
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = ["settings", "sync", "menu_book", "cloud", "cloud_off", "search", "cloud_done", "cloud_download"]
SIZES = [40, 48, 56, 64, 72, 80]


def raster(svg, size):
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "i.png")
        subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", png, svg], check=True)
        img = Image.open(png).convert("RGBA")
    # Ink = alpha (the icon is drawn black on transparent).
    alpha = img.getchannel("A")
    stride = (size + 7) // 8
    out = bytearray()
    for y in range(size):
        row = bytearray(stride)
        for x in range(size):
            if alpha.getpixel((x, y)) >= 128:
                row[x >> 3] |= 0x80 >> (x & 7)
        out += row
    return bytes(out)


def main():
    L = []
    P = L.append
    P("#pragma once")
    P("")
    P("// AUTO-GENERATED by tools/gen_ui_icons.py - do not edit by hand.")
    P("// Icons: Material Symbols (Google, Apache License 2.0), from tools/icons/*.svg,")
    P("// 1 bit a pixel, MSB first, rows padded to whole bytes.")
    P("")
    P("#include <stdint.h>")
    P("")
    P("namespace uikit {")
    P("namespace icons {")
    P("")
    P("struct IconSize {")
    P("    uint8_t size;   // width = height, pixels")
    P("    const uint8_t* bits;")
    P("};")
    P("")
    total = 0
    for name in ICONS:
        svg = os.path.join(ROOT, "tools", "icons", name + ".svg")
        cname = "".join(p.capitalize() for p in name.split("_"))
        for size in SIZES:
            data = raster(svg, size)
            total += len(data)
            P(f"inline constexpr uint8_t k{cname}{size}[] = {{")
            for i in range(0, len(data), 24):
                P("    " + ",".join(f"0x{b:02X}" for b in data[i : i + 24]) + ",")
            P("};")
        P(f"inline constexpr IconSize k{cname}[] = {{")
        P("    " + ", ".join(f"{{{s}, k{cname}{s}}}" for s in SIZES) + ",")
        P("};")
        P("")
    P(f"inline constexpr int kIconSizeCount = {len(SIZES)};")
    P("")
    P("}  // namespace icons")
    P("}  // namespace uikit")
    out = os.path.join(ROOT, "src", "ui", "kit", "ui_icons.h")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {out}: {total} bytes of bitmaps")


if __name__ == "__main__":
    sys.exit(main())
