#!/usr/bin/env python3
"""Generates src/ui/book_fonts.h: the book text fonts, 12..48 px in steps of 2.

Face: DejaVu Serif Condensed (Bitstream Vera license), rasterized 1 bpp with
Pillow at each size. Glyphs: ASCII, Latin-1, Cyrillic U+0400..U+045F and the
punctuation books use (dashes, quotes, ellipsis, bullet, numero sign).

Each font is a sorted code point table plus glyph metrics and packed bitmaps
(rows MSB-first, no row padding), read by FontEngine (src/ui/font.cpp).

Usage (from firmware/):
    python3 tools/gen_book_fonts.py [--fonts-dir /usr/share/fonts/truetype]
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

FACE = "dejavu/DejaVuSerifCondensed.ttf"
SIZES = list(range(12, 49, 2))
CODEPOINTS = sorted(set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x400, 0x460)) |
                    set(range(0x2010, 0x2016)) | set(range(0x2018, 0x201F)) |
                    {0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A, 0x2116})


def glyph(font, cp):
    ch = chr(cp)
    adv = round(font.getlength(ch))
    bbox = font.getbbox(ch, anchor="ls")
    if bbox is None or bbox[2] - bbox[0] <= 0 or bbox[3] - bbox[1] <= 0:
        return adv, 0, 0, 0, 0, b""
    l, t, r, b = bbox
    w, h = r - l, b - t
    img = Image.new("1", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=1, anchor="ls")
    px = img.load()
    out = bytearray()
    acc = n = 0
    for y in range(h):
        for x in range(w):
            acc = (acc << 1) | (1 if px[x, y] else 0)
            n += 1
            if n == 8:
                out.append(acc)
                acc = n = 0
    if n:
        out.append(acc << (8 - n))
    return adv, w, h, l, t, bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts-dir", default="/usr/share/fonts/truetype")
    args = ap.parse_args()
    path = os.path.join(args.fonts_dir, FACE)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(root, "src", "ui", "book_fonts.h")

    lines = [
        "// Generated by tools/gen_book_fonts.py - do not edit.",
        "// Book text: DejaVu Serif Condensed (Bitstream Vera license), 12..48 px.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace bookfonts {",
        "",
        "struct Glyph {",
        "    uint32_t offset;   // into the font's bitmap bytes",
        "    uint8_t width, height;",
        "    int8_t xOffset;    // from the pen position",
        "    int8_t yOffset;    // top of the bitmap relative to the baseline (negative = above)",
        "    uint8_t advance;",
        "};",
        "",
        "struct Font {",
        "    uint8_t pixelSize;",
        "    uint8_t ascent, descent;   // above / below the baseline",
        "    uint16_t count;",
        "    const uint16_t* codepoints;  // sorted",
        "    const Glyph* glyphs;",
        "    const uint8_t* bitmaps;",
        "};",
        "",
        f"static const uint16_t kCodepoints[{len(CODEPOINTS)}] = {{",
    ]
    for i in range(0, len(CODEPOINTS), 12):
        lines.append("    " + ", ".join(f"0x{c:04X}" for c in CODEPOINTS[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
    total = 0
    for px in SIZES:
        font = ImageFont.truetype(path, px)
        ascent, descent = font.getmetrics()
        glyphs, blob = [], bytearray()
        for cp in CODEPOINTS:
            adv, w, h, l, t, bits = glyph(font, cp)
            glyphs.append((len(blob), w, h, l, t, adv))
            blob += bits
        total += len(blob) + len(glyphs) * 10
        lines.append(f"static const uint8_t kBitmaps{px}[{max(1, len(blob))}] = {{")
        for i in range(0, len(blob), 24):
            lines.append("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        if not blob:
            lines.append("    0,")
        lines.append("};")
        lines.append(f"static const Glyph kGlyphs{px}[{len(glyphs)}] = {{")
        for g in glyphs:
            lines.append("    {%d,%d,%d,%d,%d,%d}," % g)
        lines.append("};")
        lines.append("")
    lines.append(f"static const Font kFonts[{len(SIZES)}] = {{")
    for px in SIZES:
        font = ImageFont.truetype(path, px)
        ascent, descent = font.getmetrics()
        lines.append(f"    {{{px}, {ascent}, {descent}, {len(CODEPOINTS)}, kCodepoints, kGlyphs{px}, kBitmaps{px}}},")
    lines.append("};")
    lines.append(f"static constexpr int kFontCount = {len(SIZES)};")
    lines.append("")
    lines.append("}  // namespace bookfonts")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(SIZES)} sizes, {len(CODEPOINTS)} glyphs each, ~{total // 1024} KB")


if __name__ == "__main__":
    main()
