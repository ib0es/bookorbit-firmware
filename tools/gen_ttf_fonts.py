#!/usr/bin/env python3
"""Generates src/reader/fonts/builtin_font_data.h: the TrueType family built into the
firmware, so that books read well with no card fonts.

Each face is cut down with fontTools to the characters books use (Latin with
Latin-1 and Extended-A, Cyrillic, punctuation, the fi/fl ligatures), hinting
dropped (stb_truetype does not hint), kerning kept. Also writes the cut faces
as .ttf beside the output, for /fonts on a card.

Usage (from firmware/):
    python3 tools/gen_ttf_fonts.py --name "Noto Serif" \\
        fonts/src/NotoSerif-Regular.ttf fonts/src/NotoSerif-Bold.ttf \\
        fonts/src/NotoSerif-Italic.ttf fonts/src/NotoSerif-BoldItalic.ttf
"""
import argparse
import io
import os

from fontTools import subset
from fontTools.ttLib import TTFont

UNICODES = ("U+0020-007E,U+00A0-017F,U+0192,U+02C6-02DC,U+0300-0301,U+0400-045F,U+0490-0491,"
            "U+2010-2027,U+2030-203A,U+2044,U+20AC,U+2116,U+2122,U+2212,U+FB01-FB02")
STYLES = ["regular", "bold", "italic", "bold_italic"]


def cut(path):
    opts = subset.Options()
    opts.hinting = False
    opts.desubroutinize = True
    opts.layout_features = ["kern"]
    opts.name_IDs = [0, 1, 2, 4, 6, 13, 14]   # copyright and license kept (OFL)
    opts.notdef_outline = True
    opts.glyph_names = False
    font = TTFont(path)
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(UNICODES))
    s.subset(font)
    # stb_truetype reads GPOS pair kerning only from plain (type 2) lookups:
    # extension lookups (type 9, Noto's) are unwrapped, small enough now.
    if "GPOS" in font:
        for lookup in font["GPOS"].table.LookupList.Lookup:
            if lookup.LookupType == 9:
                lookup.SubTable = [st.ExtSubTable for st in lookup.SubTable]
                lookup.LookupType = lookup.SubTable[0].LookupType if lookup.SubTable else 2
                lookup.SubTableCount = len(lookup.SubTable)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", default="src/reader/fonts/builtin_font_data.h")
    ap.add_argument("--ttf-dir", default="fonts/sd", help="where the cut faces go as .ttf")
    ap.add_argument("faces", nargs=4, help="regular, bold, italic, bold italic")
    a = ap.parse_args()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    os.makedirs(a.ttf_dir, exist_ok=True)
    lines = ["// Generated by tools/gen_ttf_fonts.py - do not edit.",
             "// %s (SIL Open Font License 1.1), cut to Latin, Cyrillic and punctuation." % a.name,
             "#pragma once", "#include <stdint.h>", "", "namespace builtinfont {", "",
             'static const char kName[] = "%s";' % a.name, ""]
    for style, path in zip(STYLES, a.faces):
        data = cut(path)
        base = os.path.splitext(os.path.basename(path))[0]
        with open(os.path.join(a.ttf_dir, base + ".ttf"), "wb") as f:
            f.write(data)
        print("%-12s %s: %d KB -> %d KB" % (style, path, os.path.getsize(path) // 1024, len(data) // 1024))
        lines.append("static const uint32_t k_%s_size = %d;" % (style, len(data)))
        lines.append("alignas(4) static const uint8_t k_%s[] = {" % style)
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace builtinfont")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
