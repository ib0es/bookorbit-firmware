import { DeviceKey, GitHubRelease } from '../types';
import { DEVICES } from '../constants/devices';

export interface FirmwareUrls {
  merged: string;
}

export const firmwareAssetName = (key: DeviceKey) => `bookorbit-${key}.bin`;
export const legacyMergedAssetName = (key: DeviceKey) => `bookorbit-${key}-merged.bin`;

/**
 * Resolves where to download firmware from. Release binaries are mirrored onto
 * GitHub Pages by CI (see tools/collect_releases.py) because github.com release
 * downloads do not send CORS headers and cannot be fetched from the browser.
 * Returns null when this release has no build for the model.
 */
export function resolveFirmwareUrls(key: DeviceKey, release: string, releases: GitHubRelease[]): FirmwareUrls | null {
  if (release === 'latest') {
    return { merged: DEVICES[key].merged };
  }
  if (release.startsWith('tag:')) {
    const tag = release.slice(4);
    const rel = releases.find((r) => r.tag_name === tag);
    const find = (name: string) => rel?.assets?.find((a) => a.name === name)?.browser_download_url ?? null;
    const url = find(firmwareAssetName(key)) || find(legacyMergedAssetName(key));
    return url ? { merged: url } : null;
  }
  return null;
}

/** Loads the release list generated by CI next to the page. */
export async function loadReleases(): Promise<GitHubRelease[]> {
  try {
    const res = await fetch('./releases.json', { cache: 'no-cache' });
    if (!res.ok) return [];
    const data = await res.json();
    return Array.isArray(data) ? data.filter((r) => r && typeof r.tag_name === 'string') : [];
  } catch {
    return [];
  }
}
